#include "delays.h"                         // Подключение библиотеки задержек

uint16_t left_us;                           // Обнуление переменной left_us
uint16_t left_ms;                           // Обнуление переменной left_ms

/*------------------------------------------------------------------------------
        Инициализация прерывания системного таймера для временной задержки
------------------------------------------------------------------------------*/
void DelayInit(void)
{
    SystemCoreClockUpdate();                // Запись системной частоты в переменную
    // SystemCoreClock
    SysTick_Config(SystemCoreClock/1000000); // Разрешение системного прерывания каждые
    // микросекунду
}

/*------------------------------------------------------------------------------
                        Подпрограмма временной задержки в мкс
------------------------------------------------------------------------------*/
void Delay_us(uint16_t time_us)
{
    // if((READ_BIT(SysTick->CTRL, SysTick_CTRL_ENABLE_Msk))) // Проверка активации прерывания от
    // системного таймера
    // {
    //      DelayInit();                    // Вызов подпрограммы инициализации
    // прерывания системного таймера
    // }

    left_us = time_us;
    while(left_us != 0)
    {
                                            // Проверка окончания цикла отсчета
    }
}

/*------------------------------------------------------------------------------
                        Подпрограмма временной задержки в мс
------------------------------------------------------------------------------*/
void Delay_ms(uint16_t time_ms)
{
    left_ms = time_ms;
    while(left_ms != 0)
    {
                                            // Проверка окончания цикла отсчета
        Delay_us(1000);                     // Установка задержки в 1 мс = 1000 мкс
        left_ms--;                          // Декремент переменной left_ms
    }
}

/*------------------------------------------------------------------------------
                          Обработчик системного прерывания
------------------------------------------------------------------------------*/
void SysTick_Handler(void)
{
    if(left_us)                             // Если переменная left_us не равна 0
    {
        left_us--;                          // Декремент переменной left_us каждую
    }                                       // микросекунду
}
