/*========================================================
  Лабораторная работа №6
  Устройство динамической индикации

  Вариант 7
  2026 + 2700 = 4726 (DEC) = 1276 (HEX)

  МК STM32F103C8T6
  Индикатор с общим анодом
========================================================*/

#include "stm32f10x.h"
#include "delays.h"

void Ports_Init(void);

// Коды символов 0-9, A-F
// Биты: H G F E D C B A
// 0 - сегмент горит, 1 - не горит

uint8_t numbers[16] = {
    0xC0, 0xF9, 0xA4, 0xB0,  // 0 1 2 3
    0x99, 0x92, 0x82, 0xF8,  // 4 5 6 7
    0x80, 0x90, 0x88, 0x83,  // 8 9 A b
    0xC6, 0xA1, 0x86, 0x8E   // C d E F
};

// ================================================
// ЗДЕСЬ МЕНЯЕМ ЧИСЛА
// ================================================

// Десятичное число 4726
uint8_t decimal[4] = {4, 7, 2, 6};

// Шестнадцатеричное число 1276
uint8_t hex[4] = {1, 2, 7, 6};

// ================================================

int main(void)
{
    uint16_t i;
    uint8_t j;
    uint8_t mode;
    uint8_t symbol;
    uint8_t code;

    DelayInit();       // Инициализация задержек
    Ports_Init();      // Инициализация портов

    while(1)
    {
        // 0 - десятичное число
        // 1 - шестнадцатеричное число

        for(mode = 0; mode < 2; mode++)
        {
            // Повторяем 125 раз (~1 секунда)
            for(i = 0; i < 125; i++)
            {
                // Перебираем четыре разряда
                for(j = 0; j < 4; j++)
                {
                    // Выбираем нужную цифру
                    if(mode == 0)
                        symbol = decimal[j];
                    else
                        symbol = hex[j];

                    // Получаем код сегментов
                    code = numbers[symbol];

                    // Выключаем все разряды
                    GPIOA->BRR = 0x0078;

                    // Сегменты A-D (PB12-PB15)
                    GPIOB->ODR = (GPIOB->ODR & 0x0FFF)
                               | ((code & 0x0F) << 12);

                    // Сегменты E-H (PA8-PA11)
                    GPIOA->ODR = (GPIOA->ODR & 0xF0FF)
                               | ((code & 0xF0) << 4);

                    // Включаем нужный разряд
                    GPIOA->BSRR = (1 << (j + 3));

                    // Задержка 2 мс
                    Delay_ms(2);
                }
            }
        }
    }
}
